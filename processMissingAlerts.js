async function processMissingAlerts() {
    console.log(`Processing ${missingAlertIds.length} missing alerts.`);

    const batchLimit = 500; // Firebase batch limit
    let processedCount = 0;
    let batchCount = 0;
    let successfulAdds = 0;
    let failedAdds = [];

    for (const alertId of missingAlertIds) {
        processedCount++;
        const alertDocRef = db.collection('alerts').doc(alertId);
        const alertDoc = await alertDocRef.get();

        if (!alertDoc.exists) {
            console.error(`Alert ${alertId} does not exist. Skipping.`);
            continue;
        }

        const alertData = alertDoc.data();
        const userRef = alertData.user;

        console.log(`[${processedCount}/${missingAlertIds.length}] Processing alert: ${alertId}, for user: ${userRef.id}`);

        const userDoc = await userRef.get();
        if (!userDoc.exists) {
            console.error(`User document ${userRef.id} does not exist. Skipping.`);
            continue;
        }

        let userAlerts = userDoc.data().alerts || [];

        // Check if the alert is already in the user's alerts array
        const alertExists = userAlerts.some(alert => alert.isEqual(alertDocRef));
        if (!alertExists) {
            console.log(`Alert ${alertId} does not exist in user ${userRef.id}'s alerts array. Adding.`);

            // Try to add the alert to the user's alerts array
            try {
                userAlerts.push(alertDocRef);

                // Update the user's alerts array
                await userRef.update({ alerts: userAlerts });

                // Re-fetch user to confirm the update
                const updatedUserDoc = await userRef.get();
                const updatedUserAlerts = updatedUserDoc.data().alerts || [];

                const wasAdded = updatedUserAlerts.some(alert => alert.isEqual(alertDocRef));
                if (wasAdded) {
                    console.log(`Alert ${alertId} successfully added to user ${userRef.id}'s alerts array.`);
                    successfulAdds++;
                } else {
                    console.error(`Failed to add alert ${alertId} to user ${userRef.id}'s alerts array after update.`);
                    failedAdds.push({
                        alertId,
                        userId: userRef.id,
                        error: 'Alert not present after update'
                    });
                }

            } catch (err) {
                console.error(`Error adding alert ${alertId} to user ${userRef.id}'s alerts array. Error: ${err.message}`);
                failedAdds.push({
                    alertId,
                    userId: userRef.id,
                    error: err.message
                });
            }
        } else {
            console.log(`Alert ${alertId} already exists in user ${userRef.id}'s alerts array. Skipping.`);
        }

        // Log progress at every 100 documents
        if (processedCount % 100 === 0) {
            console.log(`Processed ${processedCount} out of ${missingAlertIds.length} missing alerts.`);
        }
    }

    console.log(`All missing alerts processed. Total processed: ${processedCount}/${missingAlertIds.length}`);
    console.log(`Successful adds: ${successfulAdds}`);
    if (failedAdds.length > 0) {
        console.log(`Failed adds: ${failedAdds.length}. Details:`);
        failedAdds.forEach(failedAdd => {
            console.log(`Alert: ${failedAdd.alertId}, User: ${failedAdd.userId}, Error: ${failedAdd.error}`);
        });
    }
}

