// CSV Writer setup
const csvWriter = createCsvWriter({
    path: `exports/users_roles_${Date.now()}.csv`,
    header: [
        { id: 'user_id', title: 'user_id' },
        { id: 'role', title: 'role' }
    ],
    encoding: 'utf-8'
});

async function main() {
    try {
        console.log(`Fetching ${userIds.length} users...`);
        const records = [];

        // Process in batches of 10
        const batchSize = 10;
        for (let i = 0; i < userIds.length; i += batchSize) {
            const batch = userIds.slice(i, i + batchSize);

            const userPromises = batch.map(async (userId) => {
                const userDoc = await db.collection('users').doc(userId).get();

                if (!userDoc.exists) {
                    console.log(`User ${userId} not found`);
                    return { user_id: userId, role: '' };
                }

                const userData = userDoc.data();
                return {
                    user_id: userId,
                    role: userData.role || ''
                };
            });

            const batchResults = await Promise.all(userPromises);
            records.push(...batchResults);

            if ((i + batchSize) % 100 === 0 || i + batchSize >= userIds.length) {
                console.log(`Processed ${Math.min(i + batchSize, userIds.length)}/${userIds.length} users`);
            }
        }

        console.log(`Writing ${records.length} records to CSV...`);
        await csvWriter.writeRecords(records);
        console.log('CSV file was written successfully');
        process.exit(0);

    } catch (error) {
        console.error('Error:', error);
        process.exit(1);
    }
}

main();
